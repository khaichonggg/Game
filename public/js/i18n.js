// 语言：保存在 bb_settings.lang；没选过就跟浏览器语言
function initialLang() {
  try {
    const s = JSON.parse(localStorage.getItem('bb_settings') || '{}');
    if (s.lang === 'zh' || s.lang === 'en') return s.lang;
  } catch {
    /* 忽略 */
  }
  return (navigator.language || '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}
export let lang = initialLang();

export function t(key, ...args) {
  let s = lang === 'en' && EN[key] !== undefined ? EN[key] : key;
  if (args.length === 1 && args[0] && typeof args[0] === 'object') {
    const p = args[0];
    return String(s).replace(/\{(\w+)\}/g, (m, k) => (p[k] !== undefined ? p[k] : m));
  }
  return String(s).replace(/\{(\d+)\}/g, (m, i) => (args[i] !== undefined ? args[i] : ''));
}
export const hasEnglish = (key) => EN[key] !== undefined;
export const __EN = EN; // 测试用：检查有没有漏翻译

const listeners = [];
export const onLangChange = (fn) => listeners.push(fn);
export function setLang(l) {
  lang = l === 'en' ? 'en' : 'zh';
  try {
    const s = JSON.parse(localStorage.getItem('bb_settings') || '{}');
    s.lang = lang;
    localStorage.setItem('bb_settings', JSON.stringify(s));
  } catch {
    /* 忽略 */
  }
  document.documentElement.lang = lang === 'en' ? 'en' : 'zh-CN';
  applyStatic();
  for (const fn of listeners) fn(lang);
}

// 把数据目录里的中文字段换成随语言变化的 getter（渲染代码不用改）
const CJK = /[　-〿一-鿿＀-￯]/;
export function localize(obj) {
  if (Array.isArray(obj)) {
    obj.forEach((v, i) => {
      if (typeof v === 'string' && CJK.test(v)) Object.defineProperty(obj, i, { get: () => t(v), enumerable: true });
      else if (v && typeof v === 'object') localize(v);
    });
  } else if (obj && typeof obj === 'object') {
    for (const k of Object.keys(obj)) {
      const v = obj[k];
      if (typeof v === 'string' && CJK.test(v)) Object.defineProperty(obj, k, { get: () => t(v), enumerable: true });
      else if (v && typeof v === 'object') localize(v);
    }
  }
  return obj;
}

// 页面里写死的文字和 placeholder / title：第一次记下中文原文，之后按当前语言替换
const staticNodes = [];
const staticAttrs = [];
let collected = false;
export function applyStatic() {
  if (!collected) {
    collected = true;
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
    for (let n = walker.nextNode(); n; n = walker.nextNode()) {
      if (CJK.test(n.nodeValue) && !n.parentElement.closest('script, style, [data-no-i18n]')) staticNodes.push({ n, zh: n.nodeValue });
    }
    document.querySelectorAll('[placeholder], [title], [alt]').forEach((el) => {
      for (const a of ['placeholder', 'title', 'alt']) {
        const v = el.getAttribute(a);
        if (v && CJK.test(v)) staticAttrs.push({ el, a, zh: v });
      }
    });
  }
  for (const s of staticNodes) {
    const raw = s.zh;
    const core = raw.trim();
    s.n.nodeValue = raw.replace(core, t(core));
  }
  for (const s of staticAttrs) s.el.setAttribute(s.a, t(s.zh));
  document.title = t('碰碰球大乱斗');
}
